package stroom.ai.impl.tools.generation;

import stroom.ai.impl.GoldenFiles;
import stroom.ai.impl.tools.sample.ToolJson;

import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.TestFactory;

import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.IntStream;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;

/// The reader against its recorded results: `reader_cases.json` holds every read and rebuild of the reader's cases
/// (the XSLTs once each, in a table), with what each gives (a reading's digest; a rebuild's mapping, compact, and its
/// lists); and, per golden XSLT of the generator, digests of what reading it, rebuilding it with the mapping lost,
/// and rebuilding it with the mapping kept give. The recorded results are golden: regenerated by running with
/// `-DtestUpdateGoldenFiles=true`, then reviewed with `git diff` (see [GoldenFiles]; run it twice when the golden
/// XSLTs change too, as this reads them).
class TestXsltReaderCases {

    private static final String READER_CASES = "/stroom/ai/impl/tools/generation/reader_cases.json";
    private static final Map<String, Object> CASES = ReadingFixtures.json("reader_cases.json");
    private static final List<String> CODES = list(CASES.get("codes"));

    static {
        if (GoldenFiles.updating()) {
            TestXsltReaderCases.<Map<String, Object>>list(CASES.get("reads")).forEach(c -> c.put("reading",
                    reading(c)));
            TestXsltReaderCases.<Map<String, Object>>list(CASES.get("rebuilds")).forEach(c -> c.put("result",
                    rebuild(c)));
            final Map<String, Object> golden = new LinkedHashMap<>();
            ReadingFixtures.golden(".xslt").forEach(path -> golden.put(path.getFileName().toString(),
                    goldenDigests(path)));
            CASES.put("golden", golden);
            GoldenFiles.writeResource(READER_CASES, ToolJson.dumpsCompact(CASES));
        }
    }

    @TestFactory
    Stream<DynamicTest> everyRecordedReadGivesTheRecordedMapping() {
        final List<Map<String, Object>> reads = list(CASES.get("reads"));
        assertThat(reads).hasSizeGreaterThan(30);
        return IntStream.range(0, reads.size()).mapToObj(n -> {
            final Map<String, Object> c = reads.get(n);
            return DynamicTest.dynamicTest(n + " " + c.get("test"), () -> assertThat(reading(c))
                    .as("%s %s", ToolJson.dumps(XsltReader.read(code(c.get("code"))).toMap()),
                            GoldenFiles.differsFrom(READER_CASES))
                    .isEqualTo(c.get("reading")));
        });
    }

    @TestFactory
    Stream<DynamicTest> everyRecordedRebuildGivesTheRecordedXslt() {
        final List<Map<String, Object>> rebuilds = list(CASES.get("rebuilds"));
        assertThat(rebuilds).hasSizeGreaterThan(45);
        return IntStream.range(0, rebuilds.size()).mapToObj(n -> {
            final Map<String, Object> c = rebuilds.get(n);
            return DynamicTest.dynamicTest(n + " " + c.get("test"), () -> assertThat(ToolJson.dumps(rebuild(c), 1))
                    .as(GoldenFiles.differsFrom(READER_CASES))
                    .isEqualTo(ToolJson.dumps(c.get("result"), 1)));
        });
    }

    @TestFactory
    Stream<DynamicTest> everyGoldenXsltReadsAndRebuildsToItsGolden() {
        final Map<String, List<String>> golden = map(CASES.get("golden"));
        final List<Path> files = ReadingFixtures.golden(".xslt");
        assertThat(files).hasSize(golden.size());
        return files.stream().map(path -> DynamicTest.dynamicTest(path.getFileName().toString(),
                () -> assertThat(goldenDigests(path)).as(GoldenFiles.differsFrom(READER_CASES))
                        .isEqualTo(golden.get(path.getFileName().toString()))));
    }

    // The digest of what reading a recorded read's XSLT gives.
    private static String reading(final Map<String, Object> c) {
        return ReadingFixtures.digest(XsltReader.read(code(c.get("code"))).toMap());
    }

    // What a recorded rebuild gives, as the fixtures write one (the mapping compact).
    private static Map<String, Object> rebuild(final Map<String, Object> c) {
        final TranslationMapping kept = c.get("kept") == null
                ? null
                : TranslationMapping.parse(c.get("kept"));
        final Map<String, String> imported = c.get("imported") == null
                ? Map.of()
                : map(c.get("imported"));
        return result(XsltReader.rebuild(code(c.get("code")), kept, code(c.get("kept_code")), imported),
                DumpMode.COMPACT);
    }

    // The digests of what reading a golden XSLT, rebuilding it with the mapping lost and rebuilding it with the
    // mapping kept give.
    private static List<String> goldenDigests(final Path path) {
        final String code = ReadingFixtures.read(path);
        final Map<String, Object> json = GenerationFixtures.json(ReadingFixtures.read(
                path.resolveSibling(path.getFileName().toString().replace(".xslt", ".json"))));
        final TranslationMapping mapping = TranslationMapping.parse(json.get("mapping"));
        return List.of(ReadingFixtures.digest(XsltReader.read(code).toMap()),
                ReadingFixtures.digest(result(XsltReader.rebuild(code, null, null), DumpMode.ALL)),
                ReadingFixtures.digest(result(XsltReader.rebuild(code, mapping, code), DumpMode.ALL)));
    }

    // A rebuild as the fixtures write one: the mapping (dumped so), and its lists.
    private static Map<String, Object> result(final RebuiltMapping rebuilt, final DumpMode mode) {
        final Map<String, Object> out = new LinkedHashMap<>();
        out.put("mapping", rebuilt.mapping() == null
                ? null
                : rebuilt.mapping().toJson(mode));
        out.put("reused", rebuilt.reused());
        out.put("new", rebuilt.added());
        out.put("removed", rebuilt.removed());
        out.put("raw", rebuilt.raw());
        out.put("imported_calls", rebuilt.importedCalls());
        out.put("notes", rebuilt.notes());
        out.put("problems", rebuilt.problems());
        return out;
    }

    private static String code(final Object index) {
        return index == null
                ? null
                : CODES.get(((Number) index).intValue());
    }

    @SuppressWarnings("unchecked")
    private static <T> List<T> list(final Object value) {
        return (List<T>) value;
    }

    @SuppressWarnings("unchecked")
    private static <T> Map<String, T> map(final Object value) {
        return (Map<String, T>) value;
    }
}
