package stroom.ai.impl.tools.generation;

import stroom.ai.impl.GoldenFiles;
import stroom.ai.impl.tools.sample.ToolJson;
import stroom.ai.impl.tools.validation.EventSchema;

import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.TestFactory;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.net.URISyntaxException;
import java.net.URL;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;

/// The generator against its golden files: each golden file under `golden/generation/` is a mapping a test
/// generated (named after the test), or an evaluation case's reference mapping, with what the generator gives for it
/// (problems, warnings, the events summary) and the XSLT it writes. The mapping must read to the same JSON (compact,
/// as it was given), and what is generated from it must be what the golden files hold, to the byte.
///
/// The golden files are regenerated by running with `-DtestUpdateGoldenFiles=true`, then reviewed with `git diff`
/// (see [GoldenFiles]); the mapping in each is the case's input and is kept as it is.
class TestXsltGeneratorGolden {

    private static final String DIRECTORY = "/stroom/ai/impl/golden/generation";

    @TestFactory
    Stream<DynamicTest> theGeneratedXsltIsTheGoldenToTheByte() {
        return cases().map(json -> DynamicTest.dynamicTest(json.getFileName().toString(), () -> check(json)));
    }

    @SuppressWarnings("unchecked")
    private static void check(final Path json) throws IOException {
        final String name = json.getFileName().toString();
        final Map<String, Object> golden = (Map<String, Object>) ToolJson.loads(Files.readString(json,
                StandardCharsets.UTF_8));
        final Map<String, Object> given = (Map<String, Object>) golden.get("mapping");
        final TranslationMapping mapping = TranslationMapping.fromJson(given);
        assertThat(ToolJson.dumps(mapping.toJson(DumpMode.COMPACT))).isEqualTo(ToolJson.dumps(given));
        final EventSchema schema = "3.5.2".equals(golden.get("schema"))
                ? GenerationFixtures.SCHEMA_352
                : GenerationFixtures.SCHEMA;
        final XsltGenerator.Generated generated = XsltGenerator.generate(mapping, schema,
                (String) golden.get("version"), Boolean.TRUE.equals(golden.get("mark_rules")));
        final Map<String, Object> result = new LinkedHashMap<>(generated.toMap());
        result.remove("xslt");
        final Map<String, Object> recorded = new LinkedHashMap<>(golden);
        if (golden.containsKey("full")) {
            recorded.put("full", mapping.toJson(DumpMode.ALL));
        }
        recorded.put("result", result);
        GoldenFiles.assertResourceMatches(DIRECTORY + "/" + name, ToolJson.dumps(recorded, 1));
        final String xslt = name.replace(".json", ".xslt");
        if (generated.xslt() != null) {
            GoldenFiles.assertResourceMatches(DIRECTORY + "/" + xslt, generated.xslt());
        } else {
            assertThat(json.resolveSibling(xslt)).doesNotExist();
        }
    }

    private static Stream<Path> cases() {
        try {
            final URL url = TestXsltGeneratorGolden.class.getResource(DIRECTORY);
            assertThat(url).isNotNull();
            final List<Path> files;
            try (final Stream<Path> listed = Files.list(Path.of(url.toURI()))) {
                files = listed.filter(path -> path.toString().endsWith(".json")).sorted().toList();
            }
            assertThat(files).hasSizeGreaterThan(200);
            return files.stream();
        } catch (final IOException e) {
            throw new UncheckedIOException(e);
        } catch (final URISyntaxException e) {
            throw new IllegalStateException(e);
        }
    }
}
