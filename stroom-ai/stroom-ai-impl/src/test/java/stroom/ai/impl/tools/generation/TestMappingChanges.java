import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/// A fix to a translation mapping sends only what changes (its merging; the tool's own cases are the build tool's),
/// merged into the mapping sent before. And the merging against its recorded results: `changes_cases.json` holds
/// every merge of these cases, and more, with what applying the changes (to a mapping or a plan) gives. The recorded
/// results are golden: regenerated by running with `-DtestUpdateGoldenFiles=true`, then reviewed with `git diff` (see
/// [GoldenFiles]).
class TestMappingChanges {

    private static final String CHANGES_CASES = "/stroom/ai/impl/tools/generation/changes_cases.json";
    // What a case records of applying its changes.
    private static final List<String> OUTCOME_KEYS = List.of("error", "merged", "done");

    private static final String BASE_JSON = """
            {"input": "json", "common": [{"path": "EventTime/TimeCreated", "field": "ts"},
                                         {"path": "EventDetail/Unknown/Data", "data_name": "a", "field": "a"}],
             "events": [{"name": "logon", "fields": []}, {"name": "other", "fields": []}]}""";

    @Test
    @SuppressWarnings("unchecked")
    void oneEntryOfARuleIsChangedRemovedOrAddedAndTheRestKept() {
        // Seen: a rule replaced whole meant resending all of its ~140 entries to change one, so the agent edited the
        // mapping file by hand (a dozen calls), and a rule it resent without its TypeId lost it.
        final Map<String, Object> base = json("""
                {"events": [{"name": "allow", "when": [{"field": "x-action", "equals": "allow"}],
                             "fields": [{"path": "EventDetail/TypeId", "value": "Allow"},
                                        {"path": "EventDetail/Network/Permit/Data", "data_name": "dc", "field": "dc"},
                                        {"path": "EventDetail/Network/Permit/Data", "data_name": "pop",
                                         "field": "pop"}]}]}
                """);

        final MappingChanges.Applied applied = MappingChanges.applyChanges(base, json("""
                {"events": [{"name": "allow", "fields": [
                    {"path": "EventDetail/Network/Permit/Data", "data_name": "dc", "field": "datacentre"},
                    {"path": "EventDetail/Network/Permit/Data", "data_name": "pop", "remove": true},
                    {"path": "EventDetail/Network/Permit/Destination/Port", "field": "dport"}]}]}
                """));

        final Map<String, Object> rule = ((List<Map<String, Object>>) applied.merged().get("events")).getFirst();
        assertThat(rule.get("when")).as("kept").isEqualTo(((List<Map<String, Object>>) base.get("events"))
                .getFirst().get("when"));
        assertThat(ToolJson.dumps(rule.get("fields"))).isEqualTo(ToolJson.dumps(json("""
                {"f": [{"path": "EventDetail/TypeId", "value": "Allow"},
                       {"path": "EventDetail/Network/Permit/Data", "data_name": "dc", "field": "datacentre"},
                       {"path": "EventDetail/Network/Permit/Destination/Port", "field": "dport"}]}
                """).get("f")));
        assertThat(applied.done()).containsExactly(
                "rule 'allow' entry 'EventDetail/Network/Permit/Data' (Data 'dc') replaced",
                "rule 'allow' entry 'EventDetail/Network/Permit/Data' (Data 'pop') removed",
                "rule 'allow' entry 'EventDetail/Network/Permit/Destination/Port' added");
    }

    @Test
    @SuppressWarnings("unchecked")
    void aRuleIsReplacedWholeOnlyWhenSaid() {
        final Map<String, Object> base = json("""
                {"events": [{"name": "allow", "when": [{"field": "a", "equals": "b"}],
                             "fields": [{"path": "EventDetail/TypeId", "value": "Allow"}]}]}
                """);

        final MappingChanges.Applied changedWhen = MappingChanges.applyChanges(base, json(
                "{\"events\": [{\"name\": \"allow\", \"when\": [{\"field\": \"c\", \"equals\": \"d\"}]}]}"));
        final MappingChanges.Applied replaced = MappingChanges.applyChanges(base, json(
                "{\"events\": [{\"name\": \"allow\", \"replace\": true, \"fields\": []}]}"));

        final Map<String, Object> keptFields = ((List<Map<String, Object>>) changedWhen.merged().get("events"))
                .getFirst();
        assertThat((List<?>) keptFields.get("fields")).as("its entries kept").hasSize(1);
        assertThat(changedWhen.done()).containsExactly("rule 'allow': 'when' replaced");
        final Map<String, Object> whole = ((List<Map<String, Object>>) replaced.merged().get("events")).getFirst();
        assertThat(whole).doesNotContainKeys("when", "replace");
        assertThat((List<?>) whole.get("fields")).isEmpty();
        assertThat(replaced.done()).containsExactly("rule 'allow' replaced whole");
    }

    @Test
    void anEntryOfARuleWithoutItsPathOrOneNotThereToRemoveIsRefused() {
        final Map<String, Object> base = json(
                "{\"events\": [{\"name\": \"allow\", \"fields\": []}]}");

        assertThatThrownBy(() -> MappingChanges.applyChanges(base, json(
                "{\"events\": [{\"name\": \"allow\", \"fields\": [{\"field\": \"x\"}]}]}")))
                .hasMessageStartingWith("Each entry in a rule's fields needs its path");
        assertThatThrownBy(() -> MappingChanges.applyChanges(base, json(
                "{\"events\": [{\"name\": \"allow\", \"fields\": [{\"path\": \"EventDetail/TypeId\", "
                + "\"remove\": true}]}]}")))
                .hasMessage("changes.events removes rule 'allow' entry 'EventDetail/TypeId', which the mapping "
                            + "does not have");
    }

    @TestFactory
    Stream<DynamicTest> theChangesMergeAsRecorded() {
        final List<Map<String, Object>> cases = ReadingFixtures.json("changes_cases.json");
        assertThat(cases).hasSizeGreaterThan(30);
        if (GoldenFiles.updating()) {
            cases.forEach(c -> {
                final Map<String, Object> outcome = outcome(c);
                OUTCOME_KEYS.forEach(c::remove);
                c.putAll(outcome);
            });
            GoldenFiles.writeResource(CHANGES_CASES, ToolJson.dumps(cases, 1));
        }
        return IntStream.range(0, cases.size()).mapToObj(n -> {
            final Map<String, Object> c = cases.get(n);
            return DynamicTest.dynamicTest(n + " " + ToolJson.dumps(c.get("changes")), () -> {
                final String before = ToolJson.dumps(c.get("base"));
                final Map<String, Object> recorded = new LinkedHashMap<>();
                OUTCOME_KEYS.stream().filter(c::containsKey).forEach(key -> recorded.put(key, c.get(key)));
                assertThat(ToolJson.dumps(outcome(c), 1)).as(GoldenFiles.differsFrom(CHANGES_CASES))
                        .isEqualTo(ToolJson.dumps(recorded, 1));
                // The base is left alone.
                assertThat(ToolJson.dumps(c.get("base"))).isEqualTo(before);
            });
        });
    }

    // What applying a case's changes gives, as the case records it: the merged mapping and what was done, or the
    // refusal's message.
    @SuppressWarnings("unchecked")
    private static Map<String, Object> outcome(final Map<String, Object> c) {
        final Map<String, Object> base = (Map<String, Object>) c.get("base");
        final boolean plan = "plan".equals(c.get("kind"));
        final Map<String, Object> out = new LinkedHashMap<>();
        try {
            final MappingChanges.Applied applied = apply(plan, base, c.get("changes"));
            out.put("merged", applied.merged());
            out.put("done", applied.done());
        } catch (final ToolRefusal e) {
            out.put("error", e.getMessage());
        }
        return out;
    }

    private static MappingChanges.Applied apply(final boolean plan,
                                                final Map<String, Object> base,
                                                final Object changes) {
        return plan
                ? MappingChanges.applyPlanChanges(base, changes)
                : MappingChanges.applyChanges(base, changes);
    }

    @Test
    void rulesByNameCommonEntriesByPathAndOtherKeysWhole() {
        final Map<String, Object> base = GenerationFixtures.json(BASE_JSON);
        final MappingChanges.Applied applied = MappingChanges.applyChanges(base, GenerationFixtures.json("""
                {"events": [{"name": "other", "fields": [{"path": "EventDetail/TypeId", "value": "x"}]},
                            {"name": "logoff", "fields": []}, {"name": "logon", "remove": true}],
                 "common": [{"path": "EventDetail/Unknown/Data", "data_name": "a", "field": "b"},
                            {"path": "EventTime/TimeCreated", "remove": true}],
                 "unmatched": "skip"}"""));
        final List<Map<String, Object>> rules = list(applied.merged().get("events"));
        assertThat(rules.stream().map(rule -> rule.get("name"))).containsExactly("other", "logoff");
        assertThat(ToolJson.dumps(rules.getFirst().get("fields")))
                .isEqualTo("[{\"path\": \"EventDetail/TypeId\", \"value\": \"x\"}]");
        assertThat(ToolJson.dumps(applied.merged().get("common")))
                .isEqualTo("[{\"path\": \"EventDetail/Unknown/Data\", \"data_name\": \"a\", \"field\": \"b\"}]");
        assertThat(applied.merged().get("unmatched")).isEqualTo("skip");
        // The base is left alone.
        final List<Map<String, Object>> baseRules = list(base.get("events"));
        assertThat(baseRules.getFirst()).containsEntry("name", "logon");
        // An existing rule is changed entry by entry; a new one added whole.
        assertThat(applied.done()).containsExactly("rule 'other' entry 'EventDetail/TypeId' added",
                "rule 'logoff' added after the others",
                "rule 'logon' removed", "common 'EventDetail/Unknown/Data' (Data 'a') replaced",
                "common 'EventTime/TimeCreated' removed", "'unmatched' replaced");
    }

    @Test
    void extractEntriesAreChangedOneByOneByTheFieldsTheyExtract() {
        // Seen in testing: changes.extract replaced the whole list, so the few new entries an agent sent wiped the
        // rest (26 cut to 2), and every record fell to the rule for the rest.
        final Map<String, Object> base = json("""
                {"input": "data_splitter",
                 "extract": [{"field": "message", "regex": "^(\\\\S+) (.*)$", "names": ["prog", "body"]},
                             {"field": "body", "regex": "^user (\\\\S+)$", "names": ["user"]},
                             {"field": "body", "regex": "^ip (\\\\S+)$", "names": ["ip"]}],
                 "common": [], "events": []}""");

        final MappingChanges.Applied applied = MappingChanges.applyChanges(base, json("""
                {"extract": [{"field": "body", "regex": "^ *user (\\\\S+)$", "names": ["user"]},
                             {"names": ["ip"], "remove": true},
                             {"field": "body", "regex": "^code (\\\\d+)$", "names": ["code"]}]}"""));

        final List<Map<String, Object>> extracts = list(applied.merged().get("extract"));
        assertThat(extracts.stream().map(entry -> entry.get("names")))
                .containsExactly(List.of("prog", "body"), List.of("user"), List.of("code"));
        assertThat(extracts.get(1).get("regex")).isEqualTo("^ *user (\\S+)$");
        assertThat(applied.done()).containsExactly("extract user replaced", "extract ip removed",
                "extract code added");
        assertThatThrownBy(() -> MappingChanges.applyChanges(base, json("""
                {"extract": [{"field": "body", "regex": "^(.*)$"}]}""")))
                .isInstanceOf(ToolRefusal.class)
                .hasMessageContaining("needs its names")
                .hasMessageContaining("prog, body; user; ip");
        assertThatThrownBy(() -> MappingChanges.applyChanges(base, json("""
                {"extract": [{"names": ["user", "ip"], "field": "body", "regex": "^(\\\\S+) (\\\\S+)$"}]}""")))
                .hasMessageContaining("are extracted by 2 entries");
    }

    @ParameterizedTest
    @MethodSource("refused")
    void changesThatCannotApplyAreRefused(final String changes, final String message) {
        final Map<String, Object> base = GenerationFixtures.json(BASE_JSON);
        assertThatThrownBy(() -> MappingChanges.applyChanges(base, GenerationFixtures.json(changes)))
                .isInstanceOf(ToolRefusal.class)
                .hasMessageContaining(message);
    }

    private static Stream<Arguments> refused() {
        return Stream.of(
                Arguments.of("{}", "only what changes"),
                Arguments.of("{\"events\": [{\"fields\": []}]}", "needs its name"),
                Arguments.of("{\"events\": [{\"name\": \"nope\", \"remove\": true}]}",
                        "removes rule 'nope', which the mapping does not have"),
                Arguments.of("{\"common\": [{\"value\": \"x\"}]}", "needs its path"));
    }

    @SuppressWarnings("unchecked")
    private static <T> List<T> list(final Object value) {
        return (List<T>) value;
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> json(final String text) {
        return (Map<String, Object>) ToolJson.loads(text);
    }
}
