package stroom.ai.impl.tools.draft;

import stroom.ai.impl.GoldenFiles;
import stroom.ai.impl.tools.generation.TranslationMapping;
import stroom.ai.impl.tools.sample.SplitterDryRun;
import stroom.ai.impl.tools.sample.SplitterSpec;
import stroom.ai.impl.tools.sample.ToolJson;

import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.TestFactory;

import java.util.ArrayList;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;

/// The draft and the sample check against their recorded results: the draft over every evaluation case's samples (as
/// the user shows them, with the case's own splitter where it has one, and the first lines of its files) and the
/// format samples; the sample's records, the mapping check and the schema values check for each case's reference
/// mapping and for each draft; and the splitter written for every spec those infer or give. The recorded results are
/// golden: regenerated by running with `-DtestUpdateGoldenFiles=true`, then reviewed with `git diff` (see
/// [GoldenFiles]).
class TestDraftCases extends DraftFixtures {

    private static final String DRAFT_CASES = "/stroom/ai/impl/tools/draft/draft_cases.json";
    private static final String LOCALCHECK_CASES = "/stroom/ai/impl/tools/draft/localcheck_cases.json";
    private static final String SPLITTER_CASES = "/stroom/ai/impl/tools/draft/splitter_cases.json";
    private static final List<Map<String, Object>> DRAFTS = cases("draft_cases.json");

    @TestFactory
    Stream<DynamicTest> theDraftsAreTheRecordedOnes() {
        if (GoldenFiles.updating()) {
            DRAFTS.forEach(entry -> entry.put("result", drafted(entry)));
            GoldenFiles.writeResource(DRAFT_CASES, ToolJson.dumps(DRAFTS, 1, false));
        }
        return DRAFTS.stream().map(entry -> DynamicTest.dynamicTest((String) entry.get("name"),
                () -> assertThat(ToolJson.dumps(drafted(entry), 1)).as(GoldenFiles.differsFrom(DRAFT_CASES))
                        .isEqualTo(ToolJson.dumps(entry.get("result"), 1))));
    }

    @TestFactory
    Stream<DynamicTest> theSampleChecksAreTheRecordedOnes() {
        final Map<String, Object> samples = new LinkedHashMap<>();
        DRAFTS.forEach(entry -> samples.put((String) entry.get("name"), entry.get("samples")));
        final List<Map<String, Object>> checks = cases("localcheck_cases.json");
        if (GoldenFiles.updating()) {
            checks.forEach(entry -> entry.put("result", checked(entry, samples)));
            GoldenFiles.writeResource(LOCALCHECK_CASES, ToolJson.dumps(checks, 1, false));
        }
        return checks.stream().map(entry -> DynamicTest.dynamicTest((String) entry.get("name"),
                () -> assertThat(ToolJson.dumps(checked(entry, samples), 1))
                        .as(GoldenFiles.differsFrom(LOCALCHECK_CASES))
                        .isEqualTo(ToolJson.dumps(entry.get("result"), 1))));
    }

    @TestFactory
    Stream<DynamicTest> theSplittersAreTheRecordedOnes() {
        final List<Map<String, Object>> splitters = cases("splitter_cases.json");
        if (GoldenFiles.updating()) {
            splitters.forEach(entry -> entry.put("xml", SplitterXml.generateSplitter(spec(entry.get("spec")))));
            GoldenFiles.writeResource(SPLITTER_CASES, ToolJson.dumps(splitters, 1, false));
        }
        return splitters.stream().map(entry -> DynamicTest.dynamicTest((String) entry.get("name"),
                () -> assertThat(SplitterXml.generateSplitter(spec(entry.get("spec"))))
                        .as(GoldenFiles.differsFrom(SPLITTER_CASES))
                        .isEqualTo(entry.get("xml"))));
    }

    // A draft case's result: the draft, or what it was refused with.
    private static Map<String, Object> drafted(final Map<String, Object> entry) {
        try {
            return drafted(entry, spec(entry.get("splitter")));
        } catch (final RuntimeException e) {
            return refused(e);
        }
    }

    // A sample check case's result: the check, or what it was refused with.
    private static Map<String, Object> checked(final Map<String, Object> entry, final Map<String, Object> samples) {
        final List<String> texts = entry.containsKey("texts")
                ? texts(entry.get("texts"))
                : texts(samples.get((String) entry.get("draft")));
        try {
            return checked(entry, texts);
        } catch (final RuntimeException e) {
            return refused(e);
        }
    }

    // A refusal, as the cases record one: the exception's kind and message.
    private static Map<String, Object> refused(final RuntimeException e) {
        final Map<String, Object> out = new LinkedHashMap<>();
        out.put("error", e.getClass().getSimpleName() + ": " + e.getMessage());
        return out;
    }

    @SuppressWarnings("unchecked")
    private static Map<String, Object> drafted(final Map<String, Object> entry, final SplitterSpec splitter) {
        final Function<String, String> detailCheck = Boolean.TRUE.equals(entry.get("detail_check"))
                ? detail -> SourceNotes.detailProblem(SCHEMA, detail)
                : null;
        return DraftMapping.draft(entry.get("samples"), (String) entry.get("source_name"),
                (String) entry.get("system_name"), (String) entry.get("environment"),
                (Map<String, Object>) entry.get("source_notes"), detailCheck, splitter);
    }

    @SuppressWarnings("unchecked")
    private static List<String> texts(final Object samples) {
        if (samples instanceof final Map<?, ?> map) {
            return new ArrayList<>((Collection<String>) map.values());
        }
        if (samples instanceof final String text) {
            return new ArrayList<>(List.of(text));
        }
        return new ArrayList<>((List<String>) samples);
    }

    private static Map<String, Object> checked(final Map<String, Object> entry, final List<String> texts) {
        final TranslationMapping mapping = mapping(entry.get("mapping"));
        SplitterSpec spec = null;
        if ("data_splitter".equals(mapping.input())) {
            final Object given = entry.get("splitter");
            if ("infer".equals(given)) {
                spec = inferred(texts.getFirst());
            } else {
                spec = spec(given);
            }
        }
        final LocalCheck.SampleRecords records = LocalCheck.sampleRecords(mapping, texts, spec);
        final Map<String, Object> out = new LinkedHashMap<>();
        out.put("splitter", spec == null
                ? null
                : spec.toMap());
        out.put("note", records.note());
        out.put("records", records.records().size());
        out.put("check", LocalCheck.checkMapping(mapping, records.records()));
        out.put("schema_values", LocalCheck.checkSchemaValues(mapping, records.records(), SCHEMA));
        return out;
    }

    private static SplitterSpec inferred(final String text) {
        try {
            return SplitterDryRun.inferSpec(text).spec();
        } catch (final RuntimeException e) {
            return null;
        }
    }
}
